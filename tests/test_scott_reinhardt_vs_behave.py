"""Scott & Reinhardt (2001) outputs against the BehavePlus engine (tests/reference/behave_crown_sr_reference.csv,
generated by behave_crown_sr_driver.cpp, engine commit d4acc8a)."""
import os
import numpy as np
import pandas as pd
from rothcruz import BEHAVE_COMPAT, scott_reinhardt

REF = os.path.join(os.path.dirname(__file__), "reference", "behave_crown_sr_reference.csv")


def _rel(a, b):
    a, b = np.asarray(a, float), np.asarray(b, float)
    return np.abs(a - b) / np.maximum(np.abs(b), 1e-12)


def run(path=REF):
    ref = pd.read_csv(path); worst = dict(cfb=0, final_ros=0, final_ib=0, o_active=0); mism = 0; bad = []
    for fm, g in ref.groupby("fm"):
        r = scott_reinhardt(fm, g.m1, g.m10, g.m100, g.mlh, g.mlw, g.fmc, g.wind20_kmh, g.slope_pct, g.cbh_m, g.cbd,
                            g.cc_pct, g.ch_m, None, options=BEHAVE_COMPAT)
        worst["cfb"] = max(worst["cfb"], float(np.max(np.abs(r["cfb"] - g.cfb.values))))
        worst["final_ros"] = max(worst["final_ros"], float(np.max(_rel(r["final_ros"], g.final_ros_mmin))))
        worst["final_ib"] = max(worst["final_ib"], float(np.max(_rel(r["final_ib"], g.final_ib_kwm))))
        worst["o_active"] = max(worst["o_active"], float(np.max(_rel(r["o_active_kmh"], g.o_active_kmh))))
        m = r["fire_type"] != g.fire_type.values; mism += int(m.sum())
        if m.any(): bad.append((fm, int(m.sum())))
    return worst, mism, bad


def test_scott_reinhardt_vs_behaveplus():
    worst, mism, bad = run()
    assert mism == 0, bad
    assert worst["cfb"] < 1e-5 and worst["final_ros"] < 1e-5 and worst["o_active"] < 1e-6 and worst["final_ib"] < 1e-4, worst
